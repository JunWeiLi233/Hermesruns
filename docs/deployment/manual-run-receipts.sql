-- Additive manual-run replay receipt. New website: /training-plan.
-- Existing prerequisites: runner(id bigint), activities table (not modified).
-- Production currently uses Hibernate update; this reviewed equivalent is for deployments
-- that apply schema changes explicitly before starting with Hibernate validate.
CREATE TABLE IF NOT EXISTS manual_run_receipt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runner_id bigint NOT NULL REFERENCES runner(id) ON DELETE CASCADE,
    client_key varchar(36) NOT NULL,
    request_hash varchar(64) NOT NULL,
    activity_id bigint,
    deleted boolean NOT NULL,
    started_at timestamp with time zone,
    time_zone varchar(64),
    distance_meters integer,
    elapsed_seconds integer,
    name varchar(120),
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT uk_manual_run_owner_key UNIQUE(runner_id, client_key)
);
CREATE INDEX IF NOT EXISTS idx_manual_run_activity ON manual_run_receipt(activity_id);
-- Activity ID is intentionally a scalar: deleting an activity redacts its replay receipt via
-- ActivityDeletionHook. Retain only the save key/hash/owner/creation time after that deletion.
-- RunnerDataPurger deletes every receipt during account deletion, including soft deletion.
