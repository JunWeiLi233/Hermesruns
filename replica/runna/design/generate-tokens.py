"""Generate native, CSS and optional web Tailwind adapters from one token file."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
token = json.loads((ROOT / 'tokens.json').read_text(encoding='utf-8'))
lines = ['/* Generated by generate-tokens.py; edit tokens.json. */', ':root {']
for key, value in token['color'].items():
    lines.append(f'  --color-{key}: {value};')
for key, value in token['type'].items():
    for prop, unit in [('size','px'),('line','px'),('weight','')]:
        lines.append(f'  --type-{key}-{prop}: {value[prop]}{unit};')
for value in token['space']:
    lines.append(f'  --space-{value}: {value}px;')
for key, value in token['radius'].items():
    lines.append(f'  --radius-{key}: {value}px;')
for key, value in token['layout'].items():
    lines.append(f'  --layout-{key}: {value}px;')
for key, value in token['component'].items():
    lines.append(f'  --component-{key}: {value}px;')
for key, value in token['shadow'].items():
    lines.append(f'  --shadow-{key}: {value};')
for key, value in token['motion'].items():
    lines.append(f'  --motion-{key}: {value};')
lines += [f"  --font-sans: {token['font']['sans']};", '}']
(ROOT/'tokens.css').write_text('\n'.join(lines)+'\n',encoding='utf-8')
native = {k:v for k,v in token.items() if not k.startswith('_') and k not in ['pairs','shadow','font','motion']}
(ROOT/'tokens.ts').write_text('// Generated by generate-tokens.py; edit tokens.json.\nexport const tokens = '+json.dumps(native,indent=2)+' as const;\n',encoding='utf-8')
theme = {
    'colors':{k:f'var(--color-{k})' for k in token['color']},
    'spacing':{str(k):f'var(--space-{k})' for k in token['space']},
    'borderRadius':{k:f'var(--radius-{k})' for k in token['radius']},
    'fontFamily':{'sans':['var(--font-sans)']},
    'fontSize':{k:[f'var(--type-{k}-size)',{'lineHeight':f'var(--type-{k}-line)','fontWeight':str(v['weight'])}] for k,v in token['type'].items()}
}
(ROOT/'tailwind.config.cjs').write_text('// Optional Tailwind 3 web adapter; not used by native components.\nmodule.exports = '+json.dumps({'content':['./playground/**/*.{html,tsx}'],'theme':{'extend':theme}},indent=2)+';\n',encoding='utf-8')
v4=['/* Optional Tailwind 4 web adapter; import tokens.css first. */','@theme inline {']
for k in token['color']:
    v4.append(f'  --color-{k}: var(--app-color-{k});')
v4 += ['}', ':root {']
for k,v in token['color'].items():
    v4.append(f'  --app-color-{k}: {v};')
v4 += ['}']
(ROOT/'tailwind.theme.css').write_text('\n'.join(v4)+'\n',encoding='utf-8')
print('Generated tokens.ts, tokens.css, and optional Tailwind adapters.')
