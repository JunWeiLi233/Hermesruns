export function translateLoadingText(t, text) {
  if (typeof text !== 'string') return text;
  const caption = text.trim();
  const key = TEXT_KEYS.get(caption);
  if (!key) return text;
  const start = text.indexOf(caption);
  return text.slice(0, start) + t(key) + text.slice(start + caption.length);
}
