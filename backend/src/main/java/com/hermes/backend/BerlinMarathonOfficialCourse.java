    private static List<Map<String, Object>> routePointPayload() {
        List<Map<String, Object>> points = new ArrayList<>(ROUTE_POINTS.length);
        for (int index = 0; index < ROUTE_POINTS.length; index++) {
            double[] coordinate = ROUTE_POINTS[index];
            Map<String, Object> point = new LinkedHashMap<>();
            point.put("lat", coordinate[0]);
            point.put("lng", coordinate[1]);
            String label = labelForIndex(index);
            if (label != null) {
                point.put("label", label);
            }
            points.add(point);
        }
        return points;
    }

    private static String labelForIndex(int index) {
        if (index == 0) return "Start - Strasse des 17. Juni";
        if (index == ROUTE_INDEX_TIERGARTEN) return "Tiergarten / Moabit";
        if (index == ROUTE_INDEX_FRIEDRICHSHAIN) return "Friedrichshain east loop";
        if (index == ROUTE_INDEX_KREUZBERG) return "Kreuzberg";
        if (index == ROUTE_INDEX_SUEDSTERN) return "Suedstern";
        if (index == ROUTE_INDEX_RATHAUS) return "Rathaus Schoeneberg";
        if (index == ROUTE_INDEX_KURFUERSTENDAMM) return "Kurfuerstendamm";
        if (index == ROUTE_POINTS.length - 1) return "Finish - Brandenburg Gate";
        return null;
    }
