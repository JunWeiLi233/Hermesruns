-- Add the table used by the existing Training log and Run detail goals cards.
-- This migration adds no targets and does not change any existing run or goal.
BEGIN;
CREATE TABLE IF NOT EXISTS goal (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runner_id bigint NOT NULL REFERENCES runner(id),
    period varchar(8) NOT NULL,
    metric varchar(12) NOT NULL,
    target double precision NOT NULL,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    CONSTRAINT uk_goal_runner_period_metric UNIQUE (runner_id, period, metric)
);
CREATE INDEX IF NOT EXISTS idx_goal_runner ON goal(runner_id);
COMMIT;
