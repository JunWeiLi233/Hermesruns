-- Additive PostgreSQL schema for the merged run records, labels and pace curve.
-- Apply explicitly to a backed-up local release; normal development uses Hibernate update.
BEGIN;
ALTER TABLE activities ADD COLUMN IF NOT EXISTS route_match_group_id bigint;
ALTER TABLE activities ADD COLUMN IF NOT EXISTS records_version integer;
ALTER TABLE activities ADD COLUMN IF NOT EXISTS run_type varchar(16);
ALTER TABLE activities ADD COLUMN IF NOT EXISTS source_imported_laps_json text;
ALTER TABLE activities ADD COLUMN IF NOT EXISTS session_analysis_declarations_json text;
ALTER TABLE activities ADD COLUMN IF NOT EXISTS session_analysis_updated_at timestamp(6) with time zone;

CREATE TABLE IF NOT EXISTS activity_best_effort (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id bigint NOT NULL REFERENCES activities(id),
    runner_id bigint NOT NULL REFERENCES runner(id),
    distance_key varchar(12) NOT NULL,
    distance_meters double precision NOT NULL,
    elapsed_seconds double precision NOT NULL,
    start_offset_seconds integer,
    end_offset_seconds integer,
    estimated boolean NOT NULL,
    edited_elapsed_seconds integer,
    effective_seconds double precision NOT NULL,
    hidden boolean NOT NULL,
    local_date date NOT NULL,
    model_version integer NOT NULL,
    CONSTRAINT uk_activity_best_effort UNIQUE (activity_id, distance_key)
);
CREATE INDEX IF NOT EXISTS idx_abe_runner_distance_time ON activity_best_effort(runner_id, distance_key, effective_seconds);
CREATE INDEX IF NOT EXISTS idx_abe_runner_distance_date ON activity_best_effort(runner_id, distance_key, local_date);

CREATE TABLE IF NOT EXISTS activity_tag (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id bigint NOT NULL REFERENCES activities(id),
    runner_id bigint NOT NULL REFERENCES runner(id),
    label varchar(64) NOT NULL,
    label_key varchar(64) NOT NULL,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_activity_tag UNIQUE (activity_id, label_key)
);
CREATE INDEX IF NOT EXISTS idx_activity_tag_runner_key ON activity_tag(runner_id, label_key);

CREATE TABLE IF NOT EXISTS route_match_group (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runner_id bigint NOT NULL REFERENCES runner(id),
    start_latitude double precision NOT NULL,
    start_longitude double precision NOT NULL,
    end_latitude double precision NOT NULL,
    end_longitude double precision NOT NULL,
    distance_meters double precision NOT NULL,
    bearing_degrees double precision,
    winding integer NOT NULL,
    is_loop boolean NOT NULL,
    created_at timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_route_match_group_runner ON route_match_group(runner_id);
COMMIT;
