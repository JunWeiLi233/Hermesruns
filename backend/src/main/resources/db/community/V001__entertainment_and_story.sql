-- Apply explicitly before production startup (ddl-auto=validate).
-- Additive only: no runner, course-map, or activity records are modified.
BEGIN;
CREATE TABLE IF NOT EXISTS entertainment_groups (
    id varchar(36) PRIMARY KEY,
    runner_id bigint NOT NULL REFERENCES runner(id),
    revision bigint NOT NULL,
    last_request_id varchar(36)
);
CREATE INDEX IF NOT EXISTS idx_entertainment_group_runner ON entertainment_groups(runner_id);
CREATE TABLE IF NOT EXISTS entertainment_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id varchar(36) NOT NULL REFERENCES entertainment_groups(id),
    runner_id bigint NOT NULL REFERENCES runner(id),
    UNIQUE(group_id, runner_id)
);
CREATE INDEX IF NOT EXISTS idx_entertainment_member_runner ON entertainment_members(runner_id);
CREATE TABLE IF NOT EXISTS entertainment_slots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id varchar(36) NOT NULL REFERENCES entertainment_groups(id),
    slot_index integer NOT NULL,
    symbol varchar(16),
    runner_id bigint REFERENCES runner(id),
    UNIQUE(group_id, slot_index)
);
CREATE TABLE IF NOT EXISTS entertainment_missions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runner_id bigint NOT NULL REFERENCES runner(id),
    mission_id varchar(16) NOT NULL,
    status varchar(16) NOT NULL,
    previous_status varchar(16),
    revision bigint NOT NULL,
    last_request_id varchar(36),
    UNIQUE(runner_id, mission_id)
);
CREATE TABLE IF NOT EXISTS entertainment_preferences (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runner_id bigint NOT NULL UNIQUE REFERENCES runner(id),
    accessory varchar(16) NOT NULL,
    background varchar(16) NOT NULL,
    hidden boolean NOT NULL,
    revision bigint NOT NULL,
    last_request_id varchar(36)
);
CREATE TABLE IF NOT EXISTS entertainment_memories (
    id varchar(36) PRIMARY KEY,
    runner_id bigint NOT NULL REFERENCES runner(id),
    title varchar(160) NOT NULL,
    body varchar(2000) NOT NULL,
    literal_date varchar(10),
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    revision bigint NOT NULL,
    last_request_id varchar(36)
);
CREATE INDEX IF NOT EXISTS idx_entertainment_memory_runner ON entertainment_memories(runner_id);
CREATE TABLE IF NOT EXISTS entertainment_receipts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runner_id bigint NOT NULL REFERENCES runner(id),
    request_id varchar(36) NOT NULL,
    operation varchar(128) NOT NULL,
    fingerprint varchar(64) NOT NULL,
    result_json text NOT NULL,
    resource_id varchar(36),
    UNIQUE(runner_id, request_id)
);
CREATE TABLE IF NOT EXISTS entertainment_invites (
    id varchar(36) PRIMARY KEY,
    group_id varchar(36) NOT NULL REFERENCES entertainment_groups(id),
    recipient_account_id varchar(20) NOT NULL,
    token_hash varchar(64) NOT NULL UNIQUE,
    expires_at timestamp(6) with time zone NOT NULL,
    status varchar(16) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_entertainment_invite_group ON entertainment_invites(group_id);
CREATE INDEX IF NOT EXISTS idx_entertainment_invite_recipient ON entertainment_invites(recipient_account_id);
CREATE TABLE IF NOT EXISTS story_preferences (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runner_id bigint NOT NULL UNIQUE REFERENCES runner(id),
    mode varchar(16) NOT NULL,
    current_chapter_id varchar(32),
    current_panel varchar(16) NOT NULL
);
CREATE TABLE IF NOT EXISTS story_chapter_progress (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runner_id bigint NOT NULL REFERENCES runner(id),
    chapter_id varchar(32) NOT NULL,
    branch varchar(8),
    started_at timestamp(6) with time zone NOT NULL,
    completed_at timestamp(6) with time zone,
    UNIQUE(runner_id, chapter_id)
);
COMMIT;
